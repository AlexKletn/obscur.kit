#[doc = include_str!("contract_derive.doc/SlotModel.md")]
#[derive(Debug)]
struct SlotModel {
    #[doc = include_str!("contract_derive.doc/name.md")]
    name: String,
    #[doc = include_str!("contract_derive.doc/cardinality.md")]
    cardinality: SlotCardinality,
    #[doc = include_str!("contract_derive.doc/children.md")]
    children: Vec<String>,
}

#[doc = include_str!("contract_derive.doc/SlotCardinality.md")]
#[derive(Debug, Clone, Copy)]
enum SlotCardinality {
    #[doc = include_str!("contract_derive.doc/One.md")]
    One,
    #[doc = include_str!("contract_derive.doc/Optional.md")]
    Optional,
    #[doc = include_str!("contract_derive.doc/Many.md")]
    Many,
}

impl SlotCardinality {
    #[doc = include_str!("contract_derive.doc/variant.md")]
    fn variant(self) -> TokenStream {
        match self {
            Self::One => quote!(ExactlyOne),
            Self::Optional => quote!(Optional),
            Self::Many => quote!(Many),
        }
    }
}

impl SlotModel {
    #[doc = include_str!("contract_derive.doc/parse.md")]
    fn parse(meta: &syn::meta::ParseNestedMeta<'_>) -> Result<Self, syn::Error> {
        let mut name: Option<String> = None;
        let mut cardinality = SlotCardinality::Many;
        let mut children: Vec<String> = Vec::new();
        meta.parse_nested_meta(|inner| {
            if inner.path.is_ident("name") {
                name = Some(inner.value()?.parse::<LitStr>()?.value());
            } else if inner.path.is_ident("cardinality") {
                let word: syn::Ident = inner.value()?.parse()?;
                cardinality = match word.to_string().as_str() {
                    "one" => SlotCardinality::One,
                    "optional" => SlotCardinality::Optional,
                    "many" => SlotCardinality::Many,
                    other => {
                        return Err(inner.error(format!(
                            "unknown `cardinality` value `{other}` (expected `one`, `optional` or `many`)"
                        )));
                    }
                };
            } else if inner.path.is_ident("child") {
                children.push(inner.value()?.parse::<LitStr>()?.value());
            } else {
                return Err(inner.error("unknown `slot` key (expected `name`, `cardinality` or `child`)"));
            }
            Ok(())
        })?;
        let Some(name) = name else {
            return Err(meta.error("a `slot(...)` must give a `name = \"…\"`"));
        };
        Ok(Self {
            name,
            cardinality,
            children,
        })
    }

    #[doc = include_str!("contract_derive.doc/contract_tokens.md")]
    fn contract_tokens(&self) -> TokenStream {
        let name_sym = Literal::u32_unsuffixed(fnv32(&self.name));
        let cardinality = self.cardinality.variant();
        let children = if self.children.is_empty() {
            quote!(::obscur_kit::view::contract::ChildContract::Any)
        } else {
            let ids = self.children.iter().map(|tag| {
                let id = Literal::u64_unsuffixed(component_id(tag));
                quote!(::obscur_kit::identity::ComponentId::from_raw(#id))
            });
            quote!(::obscur_kit::view::contract::ChildContract::Only(
                ::std::vec![#(#ids),*]
            ))
        };
        quote! {
            .with_slot(::obscur_kit::view::contract::SlotContract::new(
                ::obscur_kit::identity::InternedSymbol::from_raw(#name_sym),
                ::obscur_kit::view::contract::SlotCardinality::#cardinality,
                #children,
            ))
        }
    }

    #[doc = include_str!("contract_derive.doc/surface_tokens.md")]
    fn surface_tokens(&self) -> TokenStream {
        let name = LitStr::new(&self.name, Span::call_site());
        let cardinality = self.cardinality.variant();
        let children = self.children.iter().map(|tag| {
            let tag = LitStr::new(tag, Span::call_site());
            quote!(.allowing_child(#tag))
        });
        quote! {
            .with_slot(
                ::obscur_kit::view::contract::SlotSurface::new(
                    #name,
                    ::obscur_kit::view::contract::SlotCardinality::#cardinality,
                )
                #(#children)*
            )
        }
    }
}

#[doc = include_str!("contract_derive.doc/StructAttrs.md")]
#[derive(Debug, Default)]
struct StructAttrs {
    #[doc = include_str!("contract_derive.doc/name_2.md")]
    name: Option<String>,
    #[doc = include_str!("contract_derive.doc/children_2.md")]
    children: Option<ChildrenKind>,
    #[doc = include_str!("contract_derive.doc/slots.md")]
    slots: Vec<SlotModel>,
    #[doc = include_str!("contract_derive.doc/style_scope.md")]
    style_scope: Option<StyleScopeKind>,
}

#[doc = include_str!("contract_derive.doc/StyleScopeKind.md")]
#[derive(Debug, Clone, Copy)]
enum StyleScopeKind {
    #[doc = include_str!("contract_derive.doc/Scoped.md")]
    Scoped,
    #[doc = include_str!("contract_derive.doc/Open.md")]
    Open,
}

impl StructAttrs {
    #[doc = include_str!("contract_derive.doc/parse_2.md")]
    fn parse(input: &DeriveInput) -> Result<Self, syn::Error> {
        let mut out = Self::default();
        for attr in &input.attrs {
            if !attr.path().is_ident("contract") {
                continue;
            }
            attr.parse_nested_meta(|meta| {
                if meta.path.is_ident("name") {
                    let value = meta.value()?;
                    let lit: LitStr = value.parse()?;
                    out.name = Some(lit.value());
                    Ok(())
                } else if meta.path.is_ident("children") {
                    let value = meta.value()?;
                    let lit: syn::Ident = value.parse()?;
                    out.children = Some(match lit.to_string().as_str() {
                        "any" => ChildrenKind::Any,
                        "none" => ChildrenKind::None,
                        other => {
                            return Err(meta.error(format!(
                                "unknown `children` value `{other}` (expected `any` or `none`)"
                            )));
                        }
                    });
                    Ok(())
                } else if meta.path.is_ident("slot") {
                    out.slots.push(SlotModel::parse(&meta)?);
                    Ok(())
                } else if meta.path.is_ident("style_scope") {
                    let value = meta.value()?;
                    let lit: syn::Ident = value.parse()?;
                    out.style_scope = Some(match lit.to_string().as_str() {
                        "scoped" => StyleScopeKind::Scoped,
                        "open" => StyleScopeKind::Open,
                        other => {
                            return Err(meta.error(format!(
                                "unknown `style_scope` value `{other}` (expected `scoped` or \
                                 `open`)"
                            )));
                        }
                    });
                    Ok(())
                } else {
                    Err(meta.error("unknown `contract` attribute on struct"))
                }
            })?;
        }
        Ok(out)
    }
}

