//! `FromProps`: turning a node's authored properties into a component's typed props.

use obscur_identity::InternedSymbol;

use crate::component::{FromViewValue, PropsError};
use crate::view::{ViewProperty, ViewValue};

/// Builds a component's typed [`Props`](crate::component::Component::Props) from
/// the properties an authored node carries (spec §3.1: *values flow down*).
///
/// This is the decoding half of the boundary the component model was blocked on:
/// [`Component::render`](crate::component::Component::render) takes `&Self::Props`,
/// but a `.okui` document — or an `okui!` invocation, or the runtime's retained
/// tree — only has an untyped `&[ViewProperty]`. Nothing could call `render`
/// behind a `dyn` handle without a way to cross that gap.
///
/// Implement it with `#[derive(Contract)]` rather than by hand: the derive already
/// knows each field's name, type and optionality, and — importantly — resolves
/// each property's [`InternedSymbol`] through the same registry the view tree
/// uses, so the symbols actually match.
///
/// # Absence
///
/// A property that is not present, or is present as
/// [`Null`](ViewValue::Null) (which *is* absence of a value), is absent: an
/// `Option<T>` field becomes [`None`], and a required field is a
/// [`PropsError::Missing`].
pub trait FromProps: Sized {
    /// Decodes `props` into `Self`.
    ///
    /// # Errors
    ///
    /// Returns [`PropsError::Missing`] when a required property is absent, and
    /// [`PropsError::Type`] when one is present but cannot be read as the
    /// field's type.
    fn from_props(props: &[ViewProperty]) -> Result<Self, PropsError>;
}

/// The value of the property named `name`, or [`None`] when the node does not
/// carry it.
///
/// Properties are a short unordered slice, so this is a linear scan — the same
/// shape the reconciler already uses. The **first** match wins if a node somehow
/// carries a name twice.
#[must_use]
pub fn prop_value(props: &[ViewProperty], name: InternedSymbol) -> Option<&ViewValue> {
    props
        .iter()
        .find(|prop| prop.name() == name)
        .map(ViewProperty::value)
}

/// Decodes a **required** property: absent (or `Null`) is
/// [`Missing`](PropsError::Missing), present-but-unreadable is
/// [`Type`](PropsError::Type).
///
/// Generated by `#[derive(Contract)]`; the target type is inferred from the field
/// being initialised.
///
/// # Errors
///
/// See [`PropsError`].
pub fn decode_required<T: FromViewValue>(
    props: &[ViewProperty],
    name: InternedSymbol,
) -> Result<T, PropsError> {
    match prop_value(props, name) {
        None | Some(ViewValue::Null) => Err(PropsError::Missing { name }),
        Some(value) => decode_value(value, name),
    }
}

/// Decodes an **optional** property: absent (or `Null`) is [`None`], present-but-
/// unreadable is still a [`Type`](PropsError::Type) error — an authored mistake
/// must not silently degrade into "not supplied".
///
/// Generated by `#[derive(Contract)]` for `Option<T>` fields.
///
/// # Errors
///
/// See [`PropsError`].
pub fn decode_optional<T: FromViewValue>(
    props: &[ViewProperty],
    name: InternedSymbol,
) -> Result<Option<T>, PropsError> {
    match prop_value(props, name) {
        None | Some(ViewValue::Null) => Ok(None),
        Some(value) => decode_value(value, name).map(Some),
    }
}

/// Reads one present `value` as `T`, naming `name` in the error.
///
/// # Errors
///
/// Returns [`PropsError::Type`] when `value` cannot be read as `T`.
pub fn decode_value<T: FromViewValue>(
    value: &ViewValue,
    name: InternedSymbol,
) -> Result<T, PropsError> {
    T::from_view_value(value).ok_or(PropsError::Type {
        name,
        expected: T::TYPE_NAME,
    })
}

#[cfg(test)]
mod tests {
    use super::{FromProps, decode_optional, decode_required, prop_value};
    use crate::component::PropsError;
    use crate::view::{ViewProperty, ViewValue};
    use obscur_identity::InternedSymbol;

    fn sym(raw: u32) -> InternedSymbol {
        InternedSymbol::from_raw(raw)
    }

    /// `{ #1: Text("hi"), #2: Bool(true), #3: Null }`.
    fn props() -> Vec<ViewProperty> {
        vec![
            ViewProperty::new(sym(1), ViewValue::Text("hi".into())),
            ViewProperty::new(sym(2), ViewValue::Bool(true)),
            ViewProperty::new(sym(3), ViewValue::Null),
        ]
    }

    #[test]
    fn prop_value_finds_by_symbol_and_misses_cleanly() {
        assert_eq!(prop_value(&props(), sym(2)), Some(&ViewValue::Bool(true)));
        assert_eq!(prop_value(&props(), sym(99)), None);
    }

    #[test]
    fn a_required_prop_decodes_or_reports_missing() {
        assert_eq!(decode_required::<bool>(&props(), sym(2)), Ok(true));
        assert_eq!(
            decode_required::<bool>(&props(), sym(99)),
            Err(PropsError::Missing { name: sym(99) })
        );
    }

    #[test]
    fn null_counts_as_absent_for_required_and_optional_alike() {
        // `Null` IS absence of a value, so it must not decode as "present".
        assert_eq!(
            decode_required::<bool>(&props(), sym(3)),
            Err(PropsError::Missing { name: sym(3) })
        );
        assert_eq!(decode_optional::<bool>(&props(), sym(3)), Ok(None));
    }

    #[test]
    fn an_optional_prop_is_none_when_absent_but_still_errors_on_a_bad_type() {
        assert_eq!(decode_optional::<String>(&props(), sym(99)), Ok(None));
        // The important half: a wrongly-typed value must NOT degrade to `None`,
        // or an authored mistake would look like "not supplied".
        assert_eq!(
            decode_optional::<bool>(&props(), sym(1)),
            Err(PropsError::Type {
                name: sym(1),
                expected: "bool"
            })
        );
    }

    #[test]
    fn a_wrong_type_names_the_wanted_type() {
        assert_eq!(
            decode_required::<bool>(&props(), sym(1)),
            Err(PropsError::Type {
                name: sym(1),
                expected: "bool"
            })
        );
    }

    /// A hand-written impl, standing in for what `#[derive(Contract)]` emits.
    #[derive(Debug, PartialEq)]
    struct Probe {
        label: String,
        enabled: Option<bool>,
    }

    impl FromProps for Probe {
        fn from_props(props: &[ViewProperty]) -> Result<Self, PropsError> {
            Ok(Self {
                label: decode_required(props, sym(1))?,
                enabled: decode_optional(props, sym(2))?,
            })
        }
    }

    #[test]
    fn a_props_struct_round_trips_through_the_trait() {
        assert_eq!(
            Probe::from_props(&props()),
            Ok(Probe {
                label: "hi".to_owned(),
                enabled: Some(true),
            })
        );
        // Missing the required field fails the whole decode.
        assert_eq!(
            Probe::from_props(&[]),
            Err(PropsError::Missing { name: sym(1) })
        );
    }
}
